"""
model/assumptions.py
====================
Manufacturing FP&A 3-Statement Financial Model - Input Assumptions.

Contains strongly-typed, structured dataclasses with validation for:
- 7-period model horizon (F26A, F27E, F28P, F29P, F30P, F31P, F32P)
- Product lines A & B (Sales Volume in Metric Tonnes & ASP in INR/Tonne)
- Product-specific derived RM and OVC unit costs (INR/Tonne) decoupled from ASP inflation
- Multi-factor inflation rates (RM, OVC, Fixed Operating Costs, ASP)
- Fixed assets register (Gross asset value INR, Useful life years, Salvage %) and Annual Capex
- Capital structure & debt (Long-term & Short-term facilities in INR)
- Working capital metrics (Inventory, Receivables, Payables days)

Product-Level Cost Allocation Methodology:
------------------------------------------
Product A and Product B have distinct ASPs (₹85,000/MT vs. ₹115,000/MT).
1. Model-wide RM and OVC percentages apply to each product base ASP:
     Base RM Cost per Tonne (Product i)  = Base ASP_i * RM_cost_pct
     Base OVC Cost per Tonne (Product i) = Base ASP_i * OVC_cost_pct
2. Across the portfolio, weighted total RM and OVC expenses equal exactly 52% and 9%
   of total base revenue.
3. In subsequent periods:
   - Unit RM cost/tonne inflates via rm_inflation_rate (independent of ASP).
   - Unit OVC cost/tonne inflates via ovc_inflation_rate (independent of ASP).
   - ASP/tonne inflates via asp_inflation_rate.
   - Volumes grow via product-specific annual growth paths.
This ensures zero double-counting while preserving accurate product-level contribution margins.
"""

from dataclasses import dataclass, field
from typing import Dict, List


@dataclass
class ProductAssumption:
    """Volume and Average Selling Price (ASP) assumptions for a manufactured product."""
    name: str                                  # Product identifier (e.g., 'Product A')
    base_volume_tonnes: float                  # F26A sales volume in metric tonnes (MT)
    annual_volume_growth_rates: List[float]    # Growth rates for F27E to F32P (6 forward rates)
    base_asp_inr_per_tonne: float              # F26A ASP in INR per metric tonne (INR/MT)

    def __post_init__(self):
        # We require at least 6 forward growth rates to project through F32P
        if len(self.annual_volume_growth_rates) < 6:
            raise ValueError(
                f"{self.name}: annual_volume_growth_rates must contain at least 6 rates for F27E to F32P (got {len(self.annual_volume_growth_rates)})."
            )
        if self.base_volume_tonnes < 0:
            raise ValueError(f"{self.name}: base_volume_tonnes cannot be negative.")
        if self.base_asp_inr_per_tonne <= 0:
            raise ValueError(f"{self.name}: base_asp_inr_per_tonne must be greater than zero.")
        for idx, rate in enumerate(self.annual_volume_growth_rates, start=1):
            if rate < -0.90 or rate > 3.0:
                raise ValueError(
                    f"{self.name} (Period {idx}): volume growth rate {rate:.1%} is outside realistic range (-90% to +300%)."
                )

    @property
    def base_revenue_inr(self) -> float:
        """Base year gross revenue in INR generated by this product."""
        return self.base_volume_tonnes * self.base_asp_inr_per_tonne

    def get_base_rm_cost_per_tonne_inr(self, rm_cost_pct: float) -> float:
        """
        Derives base-year Raw Material cost in INR per metric tonne for this product.
        Formula: Base ASP * Model-wide RM %
        """
        return self.base_asp_inr_per_tonne * rm_cost_pct

    def get_base_ovc_cost_per_tonne_inr(self, ovc_cost_pct: float) -> float:
        """
        Derives base-year Other Variable Cost in INR per metric tonne for this product.
        Formula: Base ASP * Model-wide OVC %
        """
        return self.base_asp_inr_per_tonne * ovc_cost_pct


@dataclass
class VariableCostAssumption:
    """
    Model-wide variable cost structure (% of revenue in base year).
    Applied to each product base ASP to establish distinct unit cost baselines.
    """
    rm_cost_pct_revenue: float                 # Base Raw Material cost as % of revenue (decimal, e.g., 0.52 = 52%)
    ovc_cost_pct_revenue: float                # Base Other Variable Costs as % of revenue (decimal, e.g., 0.09 = 9%)

    def __post_init__(self):
        if not (0.0 < self.rm_cost_pct_revenue < 1.0):
            raise ValueError("rm_cost_pct_revenue must be between 0.0 and 1.0 (exclusive).")
        if not (0.0 <= self.ovc_cost_pct_revenue < 1.0):
            raise ValueError("ovc_cost_pct_revenue must be between 0.0 and 1.0.")
        if (self.rm_cost_pct_revenue + self.ovc_cost_pct_revenue) >= 1.0:
            raise ValueError("Combined variable costs (RM + OVC) cannot equal or exceed 100% of revenue.")


@dataclass
class InflationAssumption:
    """
    Annual inflation / escalation rates across operational cost categories and selling price.
    Applied independently across projection periods:
    - rm_inflation_rate: Escalates product RM cost per tonne
    - ovc_inflation_rate: Escalates product OVC cost per tonne
    - fixed_cost_inflation_rate: Escalates fixed overheads
    - asp_inflation_rate: Escalates product selling price per tonne
    """
    rm_inflation_rate: float                   # Annual RM price inflation (decimal, e.g., 0.040 = 4.0% p.a.)
    ovc_inflation_rate: float                  # Annual OVC inflation (decimal, e.g., 0.035 = 3.5% p.a.)
    fixed_cost_inflation_rate: float           # Annual fixed cost escalation (decimal, e.g., 0.050 = 5.0% p.a.)
    asp_inflation_rate: float                  # Annual price realization escalation (decimal, e.g., 0.030 = 3.0% p.a.)

    def __post_init__(self):
        for name, rate in [
            ("rm_inflation_rate", self.rm_inflation_rate),
            ("ovc_inflation_rate", self.ovc_inflation_rate),
            ("fixed_cost_inflation_rate", self.fixed_cost_inflation_rate),
            ("asp_inflation_rate", self.asp_inflation_rate),
        ]:
            if not (-0.20 <= rate <= 1.00):
                raise ValueError(f"{name} must be within realistic bounds (-20% deflation to +100% inflation).")


@dataclass
class FixedAssetInput:
    """Fixed asset inputs for straight-line depreciation calculations."""
    category_name: str                         # Asset class name (e.g., 'Plant & Machinery')
    gross_asset_value_inr: float               # Gross book value / acquisition cost in INR
    useful_life_years: int                     # Useful life in years under straight-line method
    salvage_value_pct: float                   # Residual/salvage value as % of gross value (decimal, e.g., 0.05 = 5.0%)

    def __post_init__(self):
        if self.gross_asset_value_inr < 0:
            raise ValueError(f"{self.category_name}: gross_asset_value_inr cannot be negative.")
        if self.useful_life_years <= 0:
            raise ValueError(f"{self.category_name}: useful_life_years must be greater than zero.")
        if not (0.0 <= self.salvage_value_pct < 1.0):
            raise ValueError(f"{self.category_name}: salvage_value_pct must be between 0.0 and 1.0 (exclusive).")

    @property
    def salvage_value_inr(self) -> float:
        """Estimated terminal residual value in INR."""
        return self.gross_asset_value_inr * self.salvage_value_pct

    @property
    def depreciable_base_inr(self) -> float:
        """Net depreciable cost base in INR (Gross Value - Salvage Value)."""
        return self.gross_asset_value_inr - self.salvage_value_inr

    @property
    def annual_depreciation_inr(self) -> float:
        """Annual straight-line depreciation charge in INR."""
        return self.depreciable_base_inr / self.useful_life_years


@dataclass
class DebtFacilityInput:
    """Debt capital facility tranche inputs."""
    facility_type: str                         # Tranche description: 'Long-Term Debt' or 'Short-Term Debt'
    opening_balance_inr: float                 # Opening debt principal balance in INR
    annual_interest_rate: float                # Annual borrowing coupon/interest rate (decimal, e.g., 0.0925 = 9.25% p.a.)

    def __post_init__(self):
        if self.opening_balance_inr < 0:
            raise ValueError(f"{self.facility_type}: opening_balance_inr cannot be negative.")
        if not (0.0 <= self.annual_interest_rate <= 0.50):
            raise ValueError(f"{self.facility_type}: annual_interest_rate must be between 0.0% and 50.0%.")


@dataclass
class WorkingCapitalAssumption:
    """
    Working capital turnover cycle assumptions in days.
    - inventory_days: Calculated using Cost of Goods Sold (COGS)
    - receivable_days: Calculated using Gross Revenue
    - payable_days: Calculated using Raw Material & Direct Purchases
    """
    inventory_days: float                      # (Inventory / COGS) * 365
    receivable_days: float                     # (Trade Receivables / Revenue) * 365
    payable_days: float                        # (Trade Payables / Purchases) * 365

    def __post_init__(self):
        if not (0.0 <= self.inventory_days <= 365.0):
            raise ValueError("inventory_days must be between 0 and 365 days.")
        if not (0.0 <= self.receivable_days <= 365.0):
            raise ValueError("receivable_days must be between 0 and 365 days.")
        if not (0.0 <= self.payable_days <= 365.0):
            raise ValueError("payable_days must be between 0 and 365 days.")

    @property
    def cash_conversion_cycle_days(self) -> float:
        """Net operating Cash Conversion Cycle (CCC) = DSO + DIO - DPO"""
        return self.receivable_days + self.inventory_days - self.payable_days


@dataclass
class ModelAssumptions:
    """
    Consolidated Manufacturing FP&A 3-Statement Model Assumptions.
    Centralized container holding operational, asset, debt, and working capital parameters.
    """
    # 1. Model Horizon Settings
    forecast_years: int = 7                    # Standard 7-period horizon: F26A through F32P
    base_year: int = 2025                      # Base financial year (FY2025-26 -> F26A)

    # 2. Product Categories (A and B)
    product_a: ProductAssumption = field(
        default_factory=lambda: ProductAssumption(
            name="Product A",
            base_volume_tonnes=12_000.0,       # F26A sales volume: 12,000 MT
            annual_volume_growth_rates=[0.08, 0.08, 0.07, 0.06, 0.05, 0.04],  # F27E through F32P (6 rates)
            base_asp_inr_per_tonne=85_000.0,   # F26A ASP: INR 85,000 per MT
        )
    )
    product_b: ProductAssumption = field(
        default_factory=lambda: ProductAssumption(
            name="Product B",
            base_volume_tonnes=8_500.0,        # F26A sales volume: 8,500 MT
            annual_volume_growth_rates=[0.12, 0.10, 0.10, 0.08, 0.07, 0.05],  # F27E through F32P (6 rates)
            base_asp_inr_per_tonne=115_000.0,  # F26A ASP: INR 115,000 per MT
        )
    )

    # 3. Variable Cost Structure (% of revenue in base year)
    variable_costs: VariableCostAssumption = field(
        default_factory=lambda: VariableCostAssumption(
            rm_cost_pct_revenue=0.52,          # Raw Materials = 52.0% of revenue in base year
            ovc_cost_pct_revenue=0.09,         # Other Variable Costs = 9.0% of revenue in base year
        )
    )

    # 4. Multi-Factor Inflation Rates (Annual)
    inflation: InflationAssumption = field(
        default_factory=lambda: InflationAssumption(
            rm_inflation_rate=0.040,           # 4.0% p.a. RM inflation
            ovc_inflation_rate=0.035,          # 3.5% p.a. OVC inflation
            fixed_cost_inflation_rate=0.050,   # 5.0% p.a. fixed factory & admin cost escalation
            asp_inflation_rate=0.030,          # 3.0% p.a. product ASP escalation
        )
    )

    # 5. Fixed Assets Register (Straight-Line Depreciation)
    fixed_assets: List[FixedAssetInput] = field(
        default_factory=lambda: [
            FixedAssetInput(
                category_name="Plant & Machinery",
                gross_asset_value_inr=450_000_000.0,  # INR 45.0 Cr
                useful_life_years=15,                 # 15 years useful life
                salvage_value_pct=0.05,               # 5.0% salvage value
            ),
            FixedAssetInput(
                category_name="Factory Buildings",
                gross_asset_value_inr=200_000_000.0,  # INR 20.0 Cr
                useful_life_years=30,                 # 30 years useful life
                salvage_value_pct=0.05,               # 5.0% salvage value
            ),
            FixedAssetInput(
                category_name="Utilities & Heavy Equipment",
                gross_asset_value_inr=100_000_000.0,  # INR 10.0 Cr
                useful_life_years=10,                 # 10 years useful life
                salvage_value_pct=0.02,               # 2.0% salvage value
            ),
        ]
    )

    # Annual Maintenance Capex in INR (Connected to PP&E additions & CFS CFI)
    annual_capex_inr: float = 0.0              # Default 0.0 INR unless configured

    # 6. Debt Capital Facilities
    long_term_debt: DebtFacilityInput = field(
        default_factory=lambda: DebtFacilityInput(
            facility_type="Long-Term Debt",
            opening_balance_inr=250_000_000.0,        # INR 25.0 Cr term loan
            annual_interest_rate=0.0925,              # 9.25% p.a. interest
        )
    )
    short_term_debt: DebtFacilityInput = field(
        default_factory=lambda: DebtFacilityInput(
            facility_type="Short-Term Debt",
            opening_balance_inr=80_000_000.0,         # INR 8.0 Cr working capital facility
            annual_interest_rate=0.0975,              # 9.75% p.a. interest
        )
    )

    # 7. Working Capital Cycle (Turnover Days)
    working_capital: WorkingCapitalAssumption = field(
        default_factory=lambda: WorkingCapitalAssumption(
            inventory_days=65.0,                      # 65 days of COGS
            receivable_days=50.0,                     # 50 days of Revenue
            payable_days=60.0,                        # 60 days of Purchases
        )
    )

    # 8. Fixed Operating Cost Baseline & Corporate Tax
    base_fixed_costs_inr: float = 120_000_000.0       # INR 12.0 Cr base fixed overheads (admin, plant overheads)
    corporate_tax_rate: float = 0.2517                # 25.17% (Indian corporate tax rate incl. cess/surcharge)
    # 9. Phase 3 Financial Logic Parameters: Capex Depreciation Policy, Debt Amortization, Liquidity & Payout
    capex_useful_life_years: int = 15          # Composite useful life for capitalized capex additions
    capex_salvage_value_pct: float = 0.05      # Composite salvage value (5.0%) for capex additions
    lt_debt_repayment_tenure_years: int = 5    # Repayment tenure for long-term borrowings (default 5 years)
    minimum_cash_inr: float = 50_000_000.0     # Minimum year-end cash requirement (default INR 5.0 Cr)
    dividend_payout_ratio: float = 0.0         # Dividend payout ratio (% of positive PAT, default 0.0%)


    def __post_init__(self):
        if self.forecast_years != 7:
            raise ValueError("forecast_years must be exactly 7 for the F26A-F32P horizon.")
        if self.base_fixed_costs_inr < 0:
            raise ValueError("base_fixed_costs_inr cannot be negative.")
        if not (0.0 <= self.corporate_tax_rate < 1.0):
            raise ValueError("corporate_tax_rate must be between 0.0 and 1.0.")
        if self.annual_capex_inr < 0:
            raise ValueError("annual_capex_inr cannot be negative.")
        if self.capex_useful_life_years <= 0:
            raise ValueError('capex_useful_life_years must be greater than 0.')
        if not (0.0 <= self.capex_salvage_value_pct < 1.0):
            raise ValueError('capex_salvage_value_pct must be between 0.0 and 1.0.')
        if self.lt_debt_repayment_tenure_years <= 0:
            raise ValueError('lt_debt_repayment_tenure_years must be greater than 0.')
        if self.minimum_cash_inr < 0:
            raise ValueError('minimum_cash_inr cannot be negative.')
        if not (0.0 <= self.dividend_payout_ratio <= 1.0):
            raise ValueError('dividend_payout_ratio must be between 0.0 and 1.0.')

    # -------------------------------------------------------------------------
    # Baseline Portfolio Totals
    # -------------------------------------------------------------------------
    @property
    def total_base_volume_tonnes(self) -> float:
        """Total baseline sales volume in metric tonnes (Product A + Product B)."""
        return self.product_a.base_volume_tonnes + self.product_b.base_volume_tonnes

    @property
    def total_base_revenue_inr(self) -> float:
        """Total baseline revenue in INR (Product A + Product B)."""
        return self.product_a.base_revenue_inr + self.product_b.base_revenue_inr

    # -------------------------------------------------------------------------
    # Product-Specific Derived Unit Costs (INR / Metric Tonne)
    # -------------------------------------------------------------------------
    @property
    def product_a_base_rm_cost_per_tonne_inr(self) -> float:
        """Derived base RM cost in INR/MT for Product A."""
        return self.product_a.get_base_rm_cost_per_tonne_inr(self.variable_costs.rm_cost_pct_revenue)

    @property
    def product_a_base_ovc_cost_per_tonne_inr(self) -> float:
        """Derived base OVC cost in INR/MT for Product A."""
        return self.product_a.get_base_ovc_cost_per_tonne_inr(self.variable_costs.ovc_cost_pct_revenue)

    @property
    def product_b_base_rm_cost_per_tonne_inr(self) -> float:
        """Derived base RM cost in INR/MT for Product B."""
        return self.product_b.get_base_rm_cost_per_tonne_inr(self.variable_costs.rm_cost_pct_revenue)

    @property
    def product_b_base_ovc_cost_per_tonne_inr(self) -> float:
        """Derived base OVC cost in INR/MT for Product B."""
        return self.product_b.get_base_ovc_cost_per_tonne_inr(self.variable_costs.ovc_cost_pct_revenue)

    # -------------------------------------------------------------------------
    # Portfolio Aggregate Verification Properties
    # -------------------------------------------------------------------------
    @property
    def total_base_rm_cost_inr(self) -> float:
        """Total portfolio baseline RM expense in INR."""
        cost_a = self.product_a.base_volume_tonnes * self.product_a_base_rm_cost_per_tonne_inr
        cost_b = self.product_b.base_volume_tonnes * self.product_b_base_rm_cost_per_tonne_inr
        return cost_a + cost_b

    @property
    def total_base_ovc_cost_inr(self) -> float:
        """Total portfolio baseline OVC expense in INR."""
        cost_a = self.product_a.base_volume_tonnes * self.product_a_base_ovc_cost_per_tonne_inr
        cost_b = self.product_b.base_volume_tonnes * self.product_b_base_ovc_cost_per_tonne_inr
        return cost_a + cost_b